namespace SnakeGame
{
    /// <summary>
    /// Represents the possible movement directions for the snake.
    /// </summary>
    public enum Direction
    {
        /// <summary>
        /// Movement in the upward direction (decreasing Y coordinate).
        /// </summary>
        Up,

        /// <summary>
        /// Movement in the downward direction (increasing Y coordinate).
        /// </summary>
        Down,

        /// <summary>
        /// Movement in the left direction (decreasing X coordinate).
        /// </summary>
        Left,

        /// <summary>
        /// Movement in the right direction (increasing X coordinate).
        /// </summary>
        Right,
    }
}
